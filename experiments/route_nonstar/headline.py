"""Headline numbers across targets (written to results/headline.md; quoted in the note and report).

usage: uv run python experiments/route_nonstar/headline.py [--res DIR]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
STAR = ("CTL", "B4")


def md(df: pd.DataFrame, index=True, floatfmt=".3g") -> str:
    """Markdown table without the optional `tabulate` dependency."""
    d = df.reset_index() if index else df
    def f(v):
        if isinstance(v, float):
            return "" if np.isnan(v) else format(v, floatfmt)
        return str(v)
    lines = ["| " + " | ".join(map(str, d.columns)) + " |", "|" + "---|" * len(d.columns)]
    lines += ["| " + " | ".join(f(v) for v in row) + " |" for row in d.itertuples(index=False)]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--res", default=str(HERE / "results"))
    a = ap.parse_args()
    res = Path(a.res)
    runs = pd.read_csv(res / "runs.csv")
    tr = pd.read_csv(res / "transitions.csv.gz")
    fs = pd.read_csv(res / "fit_summary.csv")
    seq = pd.read_csv(res / "sequence.csv")
    esc = pd.read_csv(res / "escape_type.csv")
    out = ["# Headline numbers (generated by headline.py)", ""]

    # ---- run classes
    st = runs.groupby(["target", "status"]).size().unstack(fill_value=0)
    out += ["## Runs", "", f"{len(runs)} runs; status counts: "
            + ", ".join(f"{k} {v}" for k, v in runs.status.value_counts().items())
            + f"; floor-flagged at some plateau: {int(runs.floor_flagged.sum())}; with a "
            f"forgetting event: {int((runs.n_forgotten > 0).sum())}; with transient segments "
            f"merged: {int((runs.n_transients > 0).sum())}.", ""]
    bad = st[[c for c in st.columns if c != "converged"]]
    bad = bad[bad.sum(axis=1) > 0]
    if len(bad):
        out += ["Non-converged runs per target:", "", md(bad), ""]
    # where they are
    nc = runs[runs.status != "converged"].groupby(["target", "status"]).log10_sigma.agg(
        ["min", "max", "size"])
    if len(nc):
        out += ["sigma range of non-converged runs (log10):", "", md(nc), ""]

    # ---- P1: what the later plateaus are
    w = tr[(tr.segment >= 1) & (tr.log10_sigma <= -1.5) & tr.d_near.notna()].copy()
    w["star"] = w.target.str.startswith(STAR)
    w["recomb"] = w.off_recombinants.fillna("").str.len() > 0
    p1 = w.groupby("star").agg(points=("seed", "size"), canonical=("canonical", "mean"),
                               with_recombinant=("recomb", "mean"))
    out += ["## P1: are the plateaus partial-target points?", "",
            "Plateau points after the first escape, window sigmas, all seeds:", "",
            md(p1), ""]
    ks = fs[(fs.key != "origin") & (fs.n_points >= 20)].copy()
    ks["star"] = ks.target.str.startswith(STAR)
    ks["kind"] = np.where(ks.frac_canonical >= 0.9, "canonical",
                          np.where(ks.frac_canonical <= 0.1, "not canonical", "mixed"))
    ks["recomb"] = ks.off_recombinants.fillna("").astype(str).str.len() > 0
    ks["level_rs"] = ks.key.str.contains("@RS")
    t1 = ks.groupby(["star", "kind"]).agg(keys=("key", "size"), with_recombinant=("recomb", "sum"),
                                          level_matches_route_sequence=("level_rs", "sum"))
    out += ["Plateau types (target, key) with >= 20 window points:", "", md(t1), ""]

    # ---- P3: exponents per predictor
    fit = ks[ks.n_fitted >= 5]
    rows = []
    for p in ["paper", "route", "pair", "hand"]:
        for star in [False, True]:
            f = fit[fit.star == star]
            d = f[f"decision_{p}"].fillna("n/a").astype(str)
            rows.append(dict(predictor=p, targets="star controls" if star else "non-star",
                             keys=len(f), holds=int((d == "holds").sum()),
                             partial=int((d == "partial").sum()),
                             fails=int(d.str.startswith("fails").sum()),
                             no_plateau_predicted=int((d == "fails (no plateau predicted)").sum()),
                             na=int((d == "n/a").sum())))
    out += ["## P3: plateau-duration exponents (registered fits, keys with >= 5 fitted seeds)", "",
            md(pd.DataFrame(rows), index=False), ""]
    cols = ["target", "key", "n_fitted", "median", "q25", "q75", "exp_paper", "exp_route",
            "exp_pair", "exp_hand", "frac_within_paper", "frac_within_route", "frac_within_pair",
            "decision_paper", "decision_route", "decision_pair", "decision_hand",
            "eff_depth_loss_median", "frac_canonical", "off_recombinants"]
    out += ["All fitted keys:", "", md(fit[cols], index=False), ""]
    sec = ks[(ks.n_fitted < 5) & (ks.n_fitted_with_flagged.fillna(0) >= 5)]
    if len(sec):
        out += ["Keys fitted only by the secondary variants (deviation 2):", "",
                md(sec[["target", "key", "n_fitted", "n_fitted_unflagged_span1",
                        "median_unflagged_span1", "n_fitted_with_flagged", "median_with_flagged",
                        "exp_paper", "exp_route", "exp_hand"]], index=False), ""]

    # ---- P4: effective depth
    e = w[w.next_eff_depth_loss.notna() & (w.floor_flag == False)].copy()  # noqa: E712
    e["paper_c"] = e.pred_paper.fillna(0)
    e["d_route"] = (e.next_eff_depth_loss - e.route_k).abs()
    e["d_paper"] = (e.next_eff_depth_loss - e.paper_c).abs()
    p4 = e.groupby("star").agg(escapes=("seed", "size"),
                               route_within_0_5=("d_route", lambda v: float((v <= 0.5).mean())),
                               paper_within_0_5=("d_paper", lambda v: float((v <= 0.5).mean())),
                               route_median_abs_dev=("d_route", "median"))
    out += ["## P4: effective depth of each escape vs predicted depth", "",
            "(loss estimator; every escape from a non-floor-flagged plateau point, window sigmas; "
            "paper depth 0 when nothing is missing)", "", md(p4), ""]

    # ---- P2: sequence
    s = seq[seq.log10_sigma <= -1.5].copy()
    s["star"] = s.target.str.startswith(STAR)
    agg = {}
    for c in ["hit_paper", "hit_route", "hit_route_any", "hit_pair", "hit_weight"]:
        s[c + "_n"] = s[c] * s.n_transitions
    for star, g in s.groupby("star"):
        n = g.n_transitions.sum()
        agg["star controls" if star else "non-star"] = {
            c: float(g[c + "_n"].sum() / n) for c in
            ["hit_paper", "hit_route", "hit_route_any", "hit_pair", "hit_weight"]} | dict(
            escapes=int(n))
    out += ["## P2: next-step agreement (escapes from plateaus, window sigmas)", "",
            md(pd.DataFrame(agg).T, floatfmt=".3f"), ""]
    kinds = w.groupby("star").next_kind.value_counts().unstack(fill_value=0)
    out += ["Kinds of escape (learn = some pattern enters J; cleanup = none does):", "",
            md(kinds), ""]

    # ---- P5: escape type
    et = esc.merge(ks[["target", "key", "route_k_median", "median", "n_fitted"]],
                   on=["target", "key"], how="inner")
    et["k"] = et.route_k_median
    t5 = et.groupby(["k", "type"]).size().unstack(fill_value=0)
    out += ["## P5: escape type vs route-rule k* (keys with >= 20 window points)", "",
            md(t5), "",
            md(et[["target", "key", "k", "type", "slope_x", "lam_min_at_smallest", "median"]],
               index=False), ""]
    (res / "headline.md").write_text("\n".join(out))
    print("\n".join(out[:60]))


if __name__ == "__main__":
    main()
