"""Headline numbers for the note and the report, from results/*.csv -> results/headline.md.

usage: uv run python experiments/route_smallinit/headline.py [--res DIR]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
STR_COLS = ("order", "J", "J_before", "J_prev_events", "J_str", "first_pattern", "patterns", "forgotten",
            "transition", "region", "weights", "bonds", "order_dense", "order_check")


class EmptyDataError(Exception):
    pass


def read_csv(path):
    """read_csv keeping pattern strings such as 00201 as text."""
    try:
        head = pd.read_csv(path, nrows=0).columns
    except pd.errors.EmptyDataError as exc:
        raise EmptyDataError(str(exc)) from exc
    return pd.read_csv(path, dtype={c: str for c in head if c.endswith("_str") or c in STR_COLS})
SMALL = -3.0


def md(df, index=True, floatfmt=".3g"):
    """Markdown table without the optional tabulate dependency."""
    if isinstance(df, pd.Series):
        df = df.to_frame()
    if index:
        df = df.reset_index()
    def f(v):
        if isinstance(v, (float, np.floating)):
            return format(v, floatfmt) if np.isfinite(v) else str(v)
        return str(v)
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "---|" * len(df.columns)
    rows = ["| " + " | ".join(f(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join([head, sep] + rows)


def q(x):
    x = pd.Series(x).dropna()
    if not len(x):
        return "n/a"
    a, b, c = x.quantile([0.25, 0.5, 0.75])
    return f"median {b:.3g} [quartiles {a:.3g}, {c:.3g}] (n={len(x)})"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--res", default=str(HERE / "results"))
    res = Path(ap.parse_args().res)
    ev = read_csv(res / "events.csv")
    runs = read_csv(res / "runs.csv")
    cells = read_csv(res / "cells.csv")
    pl = read_csv(res / "plateaus.csv")
    try:
        c1 = read_csv(res / "c1.csv")
    except EmptyDataError:
        c1 = pd.DataFrame(columns=["slope_log_ren_vs_log_sigma"])
    fc = read_csv(res / "floor_check.csv")
    try:
        ex = read_csv(res / "exponents.csv")
    except EmptyDataError:
        ex = pd.DataFrame()
    out = []
    p = out.append
    dn = runs[runs.variant == "dense"]
    e = ev[(ev.variant == "dense") & (ev.event > 0)]
    es = e[(e.log10_sigma <= SMALL + 1e-9) & ~e.floor_flag]
    p("# Headline numbers (generated by headline.py)\n")
    p("## Census of dense runs\n")
    p(f"runs: {len(dn)}; status: {dn.status.value_counts().to_dict()}")
    p(f"behaviour: {dn.behaviour.value_counts().to_dict()}")
    for chk, x in fc.groupby("check"):
        p(f"floor check '{chk}': {len(x)} duplicates, {int(x.complete.sum())} complete (both finished), flagged {int(x.floor_flag.sum())}, rel duration diff {q(x.max_rel_duration_diff)}, max {x.max_rel_duration_diff.max():.2g}")
    p(f"vode fallback segments: {int(dn.vode_segments.sum())} in {int((dn.vode_segments > 0).sum())} runs; solver fails {int(dn.fails.sum())}")
    p("\nper target (status / behaviour counts):\n")
    p(md(pd.crosstab(dn.target, dn.status)))
    p("")
    tags = ["first_escape_mixed", "two_at_once", "forgetting", "noncanonical_plateau", "trapped", "floor_flag"]
    tab = pd.DataFrame({t: dn.groupby("target").behaviour.apply(lambda b, t=t: int(b.str.contains(t).sum())) for t in tags})
    tab["clean"] = dn.groupby("target").behaviour.apply(lambda b: int((b == "clean").sum()))
    p(md(tab))
    p("\ntrapped per target and sigma:\n")
    p(md(pd.crosstab(dn[dn.status == "trapped"].target, dn[dn.status == "trapped"].log10_sigma)))

    p("\n## (a) canonical plateaus (events k >= 1 with an entry point, sigma <= 1e-3)\n")
    x = es[es.has_entry & (es.min_depth >= 2)]
    p(f"canonical (rel dist < 0.01): {x.canonical.mean():.3f} of {len(x)}; rel dist {q(x.rel_dist_mg)}")
    p(md(pd.DataFrame({"n": x.groupby("target").size(), "frac_canonical": x.groupby("target").canonical.mean(),
                    "median_rel_dist": x.groupby("target").rel_dist_mg.median(),
                    "no_entry": es.groupby("target").has_entry.apply(lambda h: int((~h).sum()))})))
    p("\nby sigma (all targets): " + str(e[e.has_entry & (e.min_depth >= 2)].groupby("log10_sigma").canonical.mean().round(3).to_dict()))
    p("non-canonical resolved plateaus by cell (sigma <= 1e-3):")
    nc = x[~x.canonical].groupby(["target", "J_before_str", "pattern_str"]).agg(n=("seed", "size"), dist=("rel_dist_mg", "median"), LmLJ=("L_minus_LJ_mg", "median"))
    p(md(nc) if len(nc) else "none")

    p("\n## (b) sequence (transitions with J nonempty, sigma <= 1e-3)\n")
    p(f"all transitions: greedy {es.agree_greedy.mean():.3f}, pairwise {es.agree_pairwise.mean():.3f}, weight {es.agree_weight.mean():.3f} (n={len(es)})")
    dis = es[(es.pred_greedy != es.pred_pairwise) | (es.pred_greedy != es.pred_weight)]
    p(f"where the rules disagree: greedy {dis.agree_greedy.mean():.3f}, pairwise {dis.agree_pairwise.mean():.3f}, weight {dis.agree_weight.mean():.3f} (n={len(dis)})")
    gp = es[es.pred_greedy != es.pred_pairwise]
    p(f"greedy vs pairwise disagree: greedy {gp.agree_greedy.mean():.3f}, pairwise {gp.agree_pairwise.mean():.3f} (n={len(gp)}, targets {sorted(gp.target.unique())})")
    nt, ti = es[~es.tie], es[es.tie]
    p(f"no tie: greedy {nt.agree_greedy.mean():.3f} (n={len(nt)}); tie: greedy {ti.agree_greedy.mean():.3f} (n={len(ti)})")
    p("by sigma, no tie: " + str(e[~e.tie & ~e.floor_flag].groupby("log10_sigma").agree_greedy.mean().round(3).to_dict()))
    p("by sigma, tie: " + str(e[e.tie & ~e.floor_flag].groupby("log10_sigma").agree_greedy.mean().round(3).to_dict()))
    p("\ngreedy failures by cell (sigma <= 1e-3):")
    f = es[~es.agree_greedy].groupby(["target", "J_before_str", "pred_greedy_str", "pattern_str", "tie"]).size().rename("n")
    tot = es.groupby(["target", "J_before_str"]).size().rename("n_J")
    f = f.reset_index().merge(tot.reset_index(), on=["target", "J_before_str"])
    p(md(f, index=False) if len(f) else "none")
    p("\nties (sigma <= 1e-3): fraction resolved toward the heavier pattern, per cell:")
    tt = ti.groupby(["target", "J_before_str"]).agg(n=("seed", "size"), heavier=("agree_greedy", "mean"))
    p(md(tt))
    # is the tie outcome a property of the seed?
    tie_all = e[e.tie & ~e.floor_flag]
    cons = tie_all.groupby(["target", "J_before", "seed"]).pattern.nunique()
    p(f"\ntie outcome constant across sigma for a (target, J, seed): {(cons == 1).mean():.3f} of {len(cons)} seed-cells")

    p("\n## (c) exponents (per seed, window sigma in [1e-5, 1e-3])\n")
    if len(ex):
        for basis in ("event", "event_clean", "pass"):
            d = ex[(ex.variant == "dense") & (ex.basis == basis)]
            later, first = d[d.J_before != "{}"], d[d.J_before == "{}"]
            p(f"### basis {basis}")
            for c, x in later.groupby("depth"):
                p(f"later plateaus, depth {c}: exponent {q(x.exponent)}; within 0.3 of c-2: {(abs(x.exponent - (c - 2)) <= 0.3).mean():.3f}")
            d3 = later[later.depth >= 3]
            p(f"later plateaus c >= 3: within 0.3 of c-2: {(abs(d3.exponent - d3.pred_route) <= 0.3).mean():.3f} (n={len(d3)}); median |dev| {(d3.exponent - d3.pred_route).abs().median():.2g}")
            dp = d3[d3.pairwise != d3.depth]
            if len(dp):
                p(f"splice cells (pairwise != depth, c >= 3): within 0.3 of c-2 {(abs(dp.exponent - dp.pred_route) <= 0.3).mean():.3f}, of pairwise-2 {(abs(dp.exponent - dp.pred_pairwise) <= 0.3).mean():.3f} (n={len(dp)})")
            d2 = later[later.depth == 2]
            if len(d2):
                p(f"depth 2: log-law slope / 1/(s A) per cell: " + str((d2.log_slope / d2.pred_log_slope).groupby(d2.target + " " + d2.transition).median().round(3).to_dict()))
            oc = later[later.one_component_order.notna() & (later.one_component_order < later.depth)]
            if len(oc):
                p(f"|J|=1 cells with Thm 3.2 order < depth: exponent {q(oc.exponent)}; within 0.3 of order-2 {(abs(oc.exponent - (oc.one_component_order - 2)) <= 0.3).mean():.3f}; of c-2 {(abs(oc.exponent - oc.pred_route) <= 0.3).mean():.3f}")
            if len(first):
                p(f"first plateau (from the origin, c = K): exponent - (K-2) {q(first.exponent - first.pred_route)}; within 0.3: {(abs(first.exponent - first.pred_route) <= 0.3).mean():.3f}")
        r = ex[(ex.variant == "ref") & (ex.basis == "event")]
        if len(r):
            p(f"reference runs: c>=3 exponent minus (c-2): {q(r[r.depth >= 3].exponent - r[r.depth >= 3].pred_route)}")
    cc = cells[(cells.variant == "dense") & (cells.basis == "event_clean")]
    p("\nper-cell decisions (dense, basis event_clean):\n")
    cols = ["target", "transition", "pattern_str", "depth", "pairwise", "one_component_order", "n_fitted", "exp_q1", "exp_median", "exp_q3",
            "frac_within_0p3_route", "log_slope_median", "pred_log_slope", "decision_exponent"]
    p(md(cc[cc.n_fitted > 0][[c for c in cols if c in cc]], index=False))
    p("\nreference decisions:\n")
    rc = cells[(cells.variant == "ref") & (cells.n_fitted > 0) & (cells.basis == "event")]
    p(md(rc[[c for c in cols if c in rc]], index=False))

    p("\n## (d) effective depth (sigma <= 1e-3)\n")
    for c, x in es.groupby("depth"):
        p(f"depth {c}: eff {q(x.eff_depth)}; |eff - c| <= 0.3: {(abs(x.eff_depth - c) <= 0.3).mean():.3f}; nan {x.eff_depth.isna().mean():.3f}")
    e0 = ev[(ev.variant == "dense") & (ev.event == 0) & (ev.log10_sigma <= SMALL + 1e-9)]
    p(f"event 0 (from origin, depth K): eff - K {q(e0.eff_depth - e0.depth)}")
    bad = es[(abs(es.eff_depth - es.depth) > 0.3)].groupby(["target", "J_before_str", "pattern_str", "depth"]).agg(n=("seed", "size"), eff=("eff_depth", "median"))
    p("cells with mismatches:\n" + (md(bad) if len(bad) else "none"))

    p("\n## (e) closeness to the aligned manifold\n")
    p(f"peak off-target over transitions (k >= 1, sigma <= 1e-3): {q(es.peak_offtarget)}; < 1e-2: {(es.peak_offtarget < 1e-2).mean():.3f}")
    p("by target: " + str(es.groupby("target").peak_offtarget.max().apply(lambda v: f"{v:.2g}").to_dict()))
    p("by sigma (median, max): " + str(e.groupby("log10_sigma").peak_offtarget.agg(["median", "max"]).map(lambda v: float(f"{v:.2g}")).to_dict("index")))
    pls = pl[(pl.variant == "dense") & (pl.log10_sigma <= SMALL + 1e-9)]
    p(f"alignment quality at the min-gradient point: {q(pls.align_q_mg)}")

    p("\n## (f) Assumption C.1\n")
    p(f"(1) slope of log route-entry size vs log sigma: {q(c1.slope_log_ren_vs_log_sigma)}; within 0.1 of 1: {(abs(c1.slope_log_ren_vs_log_sigma - 1) <= 0.1).mean():.3f} (n={len(c1)})")
    p(f"(1) route-entry geometric mean / sigma at entry: {q(pls.ren_gmean_entry)}; spread max/min over nodes: {q(pls.ren_spread_entry)}")
    p(f"(2) gamma_obs / A_r(J) at min-gradient point: {q(pls.gamma_ratio_mg)}; within 5%: {(abs(pls.gamma_ratio_mg - 1) <= 0.05).mean():.3f}")
    p(f"(3-4) unseparated events (k >= 1, sigma <= 1e-3): {es.unseparated.mean():.3f} (n={len(es)})")
    p("by target: " + str(es.groupby("target").unseparated.mean().round(3).to_dict()))
    p("by sigma: " + str(e.groupby("log10_sigma").unseparated.mean().round(3).to_dict()))
    p(f"P_r(entry) <= 0 for the learned pattern: {(es.P_r_entry <= 0).mean():.3f}; for all missing patterns at entry: {(pls.P_entry <= 0).mean():.3f}")

    p("\n## one-step-ahead (sigma <= 1e-3, events with an entry point)\n")
    x = es[es.has_entry]
    p(f"predictor A (P_r): ratio obs/pred {q(x.onestep_ratio.replace([np.inf, -np.inf], np.nan))}; within [0.5, 2]: {x.onestep_ratio.between(0.5, 2).mean():.3f}; winner agrees: {x.agree_onestep.mean():.3f}")
    p(f"predictor B (route-entry norms): ratio {q(x.onestep_ratio_B.replace([np.inf, -np.inf], np.nan))}; within [0.5, 2]: {x.onestep_ratio_B.between(0.5, 2).mean():.3f}; winner agrees: {(x.onestep_winner_B == x.pattern).mean():.3f}")
    for c, y in x.groupby("depth"):
        p(f"  depth {c}: A {q(y.onestep_ratio)}; B {q(y.onestep_ratio_B)}")
    (res / "headline.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
